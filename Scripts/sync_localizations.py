#!/usr/bin/env python3
"""Generate shared SwiftPM/Finder resources from the app's canonical catalog.

No translation service is used at build time or at runtime. Run --check in CI.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'App/Resources/Localizable.xcstrings'
FINDER_KEYS = ['Send by Email', 'Envoyer ce dossier par e-mail', 'Other Recipient…',
               'Edit Recipients…', 'Open FileMailer…', 'Préparation avec Apple Intelligence…',
               'Préparation du message', 'Préparation du message…']

def render(values):
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    return '// Generated by Scripts/sync_localizations.py. Edit Localizable.xcstrings.\n' + ''.join(
        f'{quote(key)} = {quote(value)};\n' for key, value in sorted(values.items()))

def sync(check=False):
    catalog = json.loads(CATALOG.read_text())
    locales = sorted({locale for item in catalog['strings'].values()
                      for locale in item.get('localizations', {})})
    failures = []
    for locale in locales:
        values = {key: item['localizations'][locale]['stringUnit']['value']
                  for key, item in catalog['strings'].items()}
        targets = {
            ROOT / f'Packages/FileMailerCore/Sources/FileMailerDomain/Resources/{locale}.lproj/Localizable.strings': values,
            ROOT / f'FinderExtension/Resources/{locale}.lproj/Localizable.strings':
                {key: values[key] for key in FINDER_KEYS}
        }
        for path, strings in targets.items():
            expected = render(strings)
            if check:
                if not path.exists() or path.read_text() != expected:
                    failures.append(str(path.relative_to(ROOT)))
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(expected)
    if failures:
        raise SystemExit('Stale localization resources: ' + ', '.join(failures))
    print(f'{len(locales)} languages synchronized' if not check else f'{len(locales)} languages in sync')

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    sync(parser.parse_args().check)
